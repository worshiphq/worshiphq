"""
Builds src/lib/receipts/assets.generated.ts: the fonts and logos the PDF receipts need, embedded as base64 so
receipts can be made anywhere (a serverless function, the webhook, a signup) without reading files at run time.

Re-run only when a logo or font changes:
    pip install fonttools pillow
    python scripts/build-receipt-assets.py <folder-with-Inter-ttf-files> <wodona-dark.png> <worshiphq-logo2.png>

The three Inter files are Inter_400Regular.ttf, Inter_600SemiBold.ttf, Inter_700Bold.ttf (SIL Open Font License),
for example from the @expo-google-fonts/inter package. They are cut down to the letters we need (including the
cedi sign and the Twi letters) to keep the bundle small.
"""
import base64
import io
import os
import sys

from fontTools import subset
from PIL import Image

RANGES = "U+0020-007E,U+00A0-00FF,U+0100-017F,U+0186,U+0190,U+0254,U+025B,U+0300-0304,U+2010-2015,U+2018-201F,U+2022,U+2026,U+20AC,U+20B5,U+2116,U+2122,U+2212"


def font_b64(path):
    opts = subset.Options()
    opts.layout_features = ["kern"]
    opts.name_IDs = [1, 2, 3, 4, 6]
    opts.notdef_outline = True
    opts.glyph_names = False
    opts.hinting = False
    font = subset.load_font(path, opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(RANGES))
    s.subset(font)
    buf = io.BytesIO()
    subset.save_font(font, buf, opts)
    return base64.b64encode(buf.getvalue()).decode()


def logo_b64(path, width):
    im = Image.open(path).convert("RGBA")
    h = round(im.height * width / im.width)
    im = im.resize((width, h), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode(), im.width, im.height


def main():
    fonts_dir, wodona, whq = sys.argv[1:4]
    out = ["// GENERATED by scripts/build-receipt-assets.py. Do not edit by hand.", ""]
    for name, file in [("REGULAR", "Inter_400Regular.ttf"), ("SEMIBOLD", "Inter_600SemiBold.ttf"), ("BOLD", "Inter_700Bold.ttf")]:
        out.append(f'export const FONT_{name}_B64 = "{font_b64(os.path.join(fonts_dir, file))}";')
    for name, path, width in [("WODONA", wodona, 720), ("WORSHIPHQ", whq, 640)]:
        data, w, h = logo_b64(path, width)
        out.append(f'export const LOGO_{name}_B64 = "{data}";')
        out.append(f"export const LOGO_{name}_SIZE = {{ width: {w}, height: {h} }};")
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib", "receipts", "assets.generated.ts")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(dest), os.path.getsize(dest) // 1024, "KB")


main()
